async function call(t: TestApp, method: string, path: string, body?: unknown) {
  const init: RequestInit = { method };
  if (body !== undefined) {
    init.headers = { "content-type": "application/json" };
    init.body = JSON.stringify(body);
  }
  const res = await req(t.app, path, init);
  return { status: res.status, data: (await res.json()) as Json };
}

/** Steps for a dedicated day runner; the boss is generated by a separate runner per test when needed. */
async function app(steps: Step[], opts: { now?: string; noBossPool?: boolean; logs?: string[]; debug?: boolean } = {}) {
  const runner = scriptedRunner(steps);
  const logs = opts.logs ?? [];
  const monitor = createAiMonitor({ debug: opts.debug ?? false, log: (m) => logs.push(m) });
  const t = await makeTestApp({ now: opts.now ?? MON, ai: runner, monitor });
  return { t, runner, logs, jobs: (t.app as any).jobs as ReturnType<typeof createJobs> };
}

/** Route boss requests to a boss step and day/reroll requests to the scripted list. */
function byKind(day: Step[], boss: Step = envelope(VALID_BOSS)): Step[] {
  let i = 0;
  const pick: Step = async (r) => {
    if (r.kind === "generate_boss") return typeof boss === "function" ? boss(r) : boss;
    const s = day[Math.min(i++, day.length - 1)]!;
    return typeof s === "function" ? s(r) : s;
  };
  return [pick];
}

