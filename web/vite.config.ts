import { svelte } from '@sveltejs/vite-plugin-svelte';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { defineConfig, type Plugin } from 'vite';

/**
 * Builds /sw.js (sprint M6, architect-AC11): `VERSION` (a hash of every emitted file, so any change installs a
 * new worker and `activate` drops the old caches) + `PRECACHE` (index.html + the hashed /assets/*) + the pure
 * routing module + the worker body. Build only: dev never has a service worker (architect-AC12).
 */
function serviceWorker(): Plugin {
  const src = (f: string) => readFileSync(new URL(`./src/sw/${f}`, import.meta.url), 'utf8');
  return {
    name: 'qj-service-worker',
    apply: 'build',
    writeBundle(options, bundle) {
      const names = Object.keys(bundle).sort();
      const hash = createHash('sha256');
      for (const n of names) {
        const item = bundle[n]!;
        hash.update(n);
        hash.update(item.type === 'chunk' ? item.code : typeof item.source === 'string' ? item.source : Buffer.from(item.source));
      }
      const version = hash.digest('hex').slice(0, 12);
      const precache = ['/index.html', ...names.filter((n) => n.startsWith('assets/')).map((n) => `/${n}`)];
      const route = src('route.js').replace(/^\/\/ @ts-check\n/, '').replace(/^export /gm, '');
      const out = [
        '// Generated by vite.config.ts (qj-service-worker). Do not edit.',
        `const VERSION = ${JSON.stringify(version)};`,
        `const PRECACHE = ${JSON.stringify(precache)};`,
        route,
        src('worker.js'),
      ].join('\n');
      writeFileSync(join(options.dir ?? 'dist', 'sw.js'), out);
    },
  };
}

// Dev: Vite on localhost only (no --host), /api proxied to the Bun server (architect-AC3).
// The proxy keeps Host/Origin as localhost:5173, which the server's allowlist accepts (port is ignored).
export default defineConfig({
  plugins: [svelte(), serviceWorker()],
  define: {
    __APP_VERSION__: JSON.stringify(JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8')).version ?? '0.6.0')
  },
  server: {
    host: 'localhost',
    port: 5173,
    strictPort: true,
    proxy: { '/api': { target: 'http://127.0.0.1:4317', changeOrigin: false } }
  },
  build: {
    outDir: 'dist',
    emptyOutDir: true,
    // Never inline images as base64: stickers/decor are personal-use and must stay out of committed artifacts.
    assetsInlineLimit: 0
  }
});
